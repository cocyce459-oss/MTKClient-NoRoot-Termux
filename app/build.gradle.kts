    sourceSets {
        getByName("main") {
            assets.srcDir(mtkAssetsDir)
        }
    }

    signingConfigs {
        // Populated by CI from secrets when available; local builds fall back to
        // the debug key so `assembleRelease` always produces an installable APK.
        create("ci") {
            val storePath = providers.environmentVariable("MTK_KEYSTORE_FILE").orNull
            if (!storePath.isNullOrBlank() && File(storePath).isFile) {
                storeFile = File(storePath)
                storePassword = providers.environmentVariable("MTK_KEYSTORE_PASSWORD").orNull
                keyAlias = providers.environmentVariable("MTK_KEY_ALIAS").orNull
                keyPassword = providers.environmentVariable("MTK_KEY_PASSWORD").orNull
            }
        }
    }

    buildTypes {
        debug {
            isMinifyEnabled = false
            applicationIdSuffix = ".debug"
            versionNameSuffix = "-debug"
        }
        release {
            isMinifyEnabled = true
            isShrinkResources = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            val ciSigning = signingConfigs.getByName("ci")
            signingConfig = if (ciSigning.storeFile != null) ciSigning else signingConfigs.getByName("debug")
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }

    kotlinOptions {
        jvmTarget = "17"
    }

    buildFeatures {
        viewBinding = true
        buildConfig = true
    }

    packaging {
        resources {
            excludes += setOf("/META-INF/{AL2.0,LGPL2.1}")
        }
    }

    testOptions {
        unitTests.isReturnDefaultValues = true
    }

    lint {
        abortOnError = false
        warningsAsErrors = false
    }
}

