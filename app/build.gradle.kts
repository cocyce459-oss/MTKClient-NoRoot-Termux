// ---------------------------------------------------------------------------
// MediaTek asset vendoring
//
// The upstream engine ships ~48 MB of Download Agent binaries and ~325 KB of
// exploit payloads. Those are deliberately NOT committed to git: they are
// fetched once at build time and packaged into the APK, so the installed app is
// completely self-contained and works offline.
//
//   -PmtkclientDir=<path>   vendor from a local checkout (no network needed)
//   -PmtkclientRef=<ref>    upstream git ref to fetch (default: main)
//   -PslimAssets=true       omit Loader/ DA binaries -> BROM-only, ~2 MB APK
// ---------------------------------------------------------------------------
val mtkclientDirProp = providers.gradleProperty("mtkclientDir")
val mtkclientRef = providers.gradleProperty("mtkclientRef").getOrElse("main")
val slimAssets = providers.gradleProperty("slimAssets").getOrElse("false").toBoolean()

val mtkSrcDir = layout.buildDirectory.dir("mtkclient-src")
val mtkAssetsDir = layout.buildDirectory.dir("generated/mtkAssets")

val fetchMtkclient by tasks.registering {
    group = "mtk"
    description = "Obtain the upstream mtkclient tree (local checkout or GitHub tarball)."
    val dest = mtkSrcDir
    val localDir = mtkclientDirProp
    val ref = mtkclientRef
    outputs.dir(dest)
    doLast {
        val outRoot = dest.get().asFile
        val marker = File(outRoot, "mtkclient/payloads")
        if (marker.isDirectory) {
            logger.lifecycle("mtk: reusing cached source tree at {}", outRoot)
            return@doLast
        }

        val local = localDir.orNull
        if (!local.isNullOrBlank()) {
            val src = File(local)
            require(src.isDirectory) { "mtkclientDir does not exist: $local" }
            // Accept either a repo root or the inner mtkclient/ package dir.
            val pkg = if (File(src, "payloads").isDirectory) src.parentFile else src
            require(File(pkg, "mtkclient/payloads").isDirectory) {
                "Could not locate mtkclient/payloads under $local"
            }
            logger.lifecycle("mtk: vendoring from local checkout {}", pkg)
            copy {
                from(File(pkg, "mtkclient"))
                into(File(outRoot, "mtkclient"))
            }
            return@doLast
        }

        val tgz = layout.buildDirectory.file("mtkclient-$ref.tar.gz").get().asFile
        if (!tgz.isFile) {
            val url = "https://codeload.github.com/bkerler/mtkclient/tar.gz/refs/heads/$ref"
            logger.lifecycle("mtk: downloading {}", url)
            tgz.parentFile.mkdirs()
            URI(url).toURL().openStream().use { input ->
                tgz.outputStream().use { output -> input.copyTo(output) }
            }
        }

        val staging = File(outRoot, "_extract")
        delete(staging)
        copy {
            from(tarTree(resources.gzip(tgz)))
            into(staging)
        }
        // The tarball unpacks to a single top-level directory named after the ref.
        val unpacked = staging.listFiles()?.firstOrNull { it.isDirectory }
            ?: error("mtk: tarball contained no directory")
        copy {
            from(File(unpacked, "mtkclient"))
            into(File(outRoot, "mtkclient"))
        }
        delete(staging)
        require(marker.isDirectory) { "mtk: extraction did not produce mtkclient/payloads" }
    }
}

val syncMtkAssets by tasks.registering(Sync::class) {
    group = "mtk"
    description = "Stage the vendored payloads/loaders into the APK asset directory."
    dependsOn(fetchMtkclient)
    from(mtkSrcDir.map { it.dir("mtkclient/payloads") }) {
        into("payloads")
    }
    if (!slimAssets) {
        from(mtkSrcDir.map { it.dir("mtkclient/Loader") }) {
            into("loader")
            // 838 device-specific preloader dumps are only needed by the DA /
            // preloader-repair paths; BROM core does not read them.
            exclude("Preloader/**")
        }
    }
    into(mtkAssetsDir)
    doLast {
        val root = mtkAssetsDir.get().asFile
        val bytes = root.walkTopDown().filter { it.isFile }.sumOf { it.length() }
        logger.lifecycle("mtk: staged {} MiB of assets (slim={})", "%.2f".format(bytes / 1048576.0), slimAssets)
    }
}

